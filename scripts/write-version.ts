import fs from "fs";
import { execSync } from "child_process";

function tryExec(cmd: string): string | null {
  try {
    return execSync(cmd, {
      stdio: ["ignore", "pipe", "ignore"],
    }).toString().trim();
  } catch {
    return null;
  }
}

const major = 0;
const minor = 0;

let count: string | null = null;
count = tryExec("git rev-list --count --first-parent origin/main");
if (!count) count = tryExec("git rev-list --count HEAD");
if (!count && process.env.GITHUB_RUN_NUMBER)
  count = process.env.GITHUB_RUN_NUMBER;
if (!count && process.env.CI_BUILD_NUMBER)
  count = process.env.CI_BUILD_NUMBER;
if (!count && process.env.VERCEL_GIT_COMMIT_SHA) {
  const hex = process.env.VERCEL_GIT_COMMIT_SHA.slice(0, 7);
  try {
    count = String(parseInt(hex, 16) % 1000000);
  } catch { /* ignore */ }
}
if (!count) count = String(Math.floor(Date.now() / 1000));

const newVersion = `${major}.${minor}.${count}-alpha`;
const out = [
  "// AUTO-GENERATED by scripts/generate-version.ts — do not edit by hand.",
  "",
  `export const VERSION = "${newVersion}";`,
  "export default VERSION;",
  "",
].join("\n");

fs.mkdirSync("src/data", { recursive: true });
fs.writeFileSync("src/data/version.ts", out);
console.log("WROTE src/data/version.ts ->", newVersion);